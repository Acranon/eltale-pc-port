"""Make port/text/en_fonts.h: the optional English fonts, drawn in the game's style.

    python tools/text/gen_fonts.py > port/text/en_fonts.h

Each font (third_party/fonts, CC0) is rasterised at its own pixel size, given the game's drop shadow
(tools/text/fontlab.py), and packed into pages of 256 x height 4bpp texels (the game's font
palette: 3 ink, 1 shadow), at most 2 KiB a page so one fits the RDP's texture memory with a palette.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import fontlab

ROOT = os.path.join(HERE, "..", "..")
FONTS = [  # (name shown in the menu, file); the menu lists them in this order after "Original"
    ("Royalty Mono", "RoyaltyMono.ttf"),
    ("Quest Square", "QuestSquare.ttf"),
    ("Pixel Sans", "PixelSans.ttf"),
    ("Retro Sans", "RetroSans.ttf"),
    ("Rune Mono", "RuneMono.ttf"),
]
PAGE_W = 256
CHARS = [chr(c) for c in range(33, 127)] + ["“", "”"]


def pack(font):
    """Pages of pixel rows, and per character (code): page, s, width, x offset, advance."""
    h = font.height
    pages = [[[0] * PAGE_W for _ in range(h)]]
    x = 0
    table = {}
    for ch in CHARS:
        g = font.glyphs.get(ch)
        if not g:
            continue
        px, adv = g
        cols = [c for c in range(len(px[0])) if any(row[c] for row in px)]
        left, right = cols[0], cols[-1]
        w = right - left + 1
        if x + w > PAGE_W:
            pages.append([[0] * PAGE_W for _ in range(h)])
            x = 0
        for y in range(h):
            for c in range(w):
                pages[-1][y][x + c] = px[y][left + c]
        code = {"“": 1, "”": 2}.get(ch, ord(ch))
        table[code] = (len(pages) - 1, x, w, left, adv)
        x += w
    return pages, table


def main():
    out = ["/* Generated by tools/text/gen_fonts.py: the optional English fonts (third_party/fonts,",
           " * CC0), in pages of 256 x height 4bpp texels in the game's font palette (3 ink, 1 shadow).",
           " * Glyph entries: page, s, width, x offset, advance; char codes 1 and 2 are the curly quotes. */",
           "typedef struct { unsigned char page, s, width, xoff, advance; } EnGlyph;",
           "typedef struct { const char *name; int height, line, space, pages; const unsigned char *texels; EnGlyph glyph[128]; } EnFont;"]
    fonts = []
    for i, (name, file) in enumerate(FONTS):
        font = fontlab.TtfFont(os.path.join(ROOT, "third_party", "fonts", "sg-fonts", file))
        assert font.height <= 16, name
        pages, table = pack(font)
        data = []
        for page in pages:
            for row in page:
                data += [(row[x] << 4) | row[x + 1] for x in range(0, PAGE_W, 2)]
        out.append("static const unsigned char en_font%d_texels[%d] = {" % (i, len(data)))
        for k in range(0, len(data), 32):
            out.append("    " + ", ".join("0x%02X" % b for b in data[k:k + 32]) + ",")
        out.append("};")
        fonts.append((name, font, len(pages), table))
    out.append("static const EnFont en_fonts[%d] = {" % len(fonts))
    for i, (name, font, npages, table) in enumerate(fonts):
        glyphs = ", ".join("[%d] = { %d, %d, %d, %d, %d }" % ((c,) + table[c]) for c in sorted(table))
        out.append("    { \"%s\", %d, %d, %d, %d, en_font%d_texels, { %s } }," % (name, font.height, font.line, font.space, npages, i, glyphs))
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
